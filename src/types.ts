export type KbzPayStatus = 'completed' | 'cancelled' | 'failed';

export type KbzEnvironment = 'prod' | 'uat' | 'any';

export type KbzVerificationStatus = boolean | 'completed' | 'failed' | 'pending';

export interface KbzPayResult {
  /**
   * Numeric return code from KBZ Pay SDK.
   * 0 = Completed
   * 3 = Cancelled by user
   * -1 or others = Failed
   */
  code: number;
  /**
   * Normalized status string.
   */
  status: KbzPayStatus;
  /**
   * Merchant order ID or KBZ transaction ID if returned.
   */
  orderId?: string;
  /**
   * Error or failure message if the payment failed or was cancelled.
   */
  failMessage?: string;
}

export interface VerifyPaymentContext {
  orderId?: string;
  merchOrderId?: string;
  nativeCode?: number;
}

export interface StartKbzPayOptions {
  /**
   * The orderInfo query string generated from backend.
   * Example: "appid=...&merch_code=...&nonce_str=...&prepay_id=...&timestamp=..."
   */
  orderInfo: string;

  /**
   * The signature generated by the backend with Merchant Key.
   */
  sign: string;

  /**
   * Signature type, default is 'SHA256'.
   */
  signType?: 'SHA256' | string;

  /**
   * Optional merchant order ID. If omitted, will attempt to auto-extract from orderInfo.
   */
  merchOrderId?: string;

  /**
   * iOS only: Custom URL Scheme registered in your app to return after payment.
   * If omitted, it will automatically detect the first scheme from CFBundleURLTypes.
   */
  appScheme?: string;

  /**
   * Timeout in milliseconds for waiting for KBZ Pay callback. Default is 120000 (2 minutes).
   */
  timeoutMs?: number;

  /**
   * Optional Backend Verification Callback:
   * Highly recommended for production applications.
   * When the user returns to your app (detected via AppState active) or receives the native callback,
   * this callback is invoked to query your backend server for the authoritative payment confirmation.
   *
   * Return:
   * - true | 'completed': Payment confirmed as paid by backend
   * - false | 'failed': Payment marked as failed by backend
   * - 'pending': Payment is still pending (will continue polling up to maxPollingAttempts)
   */
  verifyPayment?: (context: VerifyPaymentContext) => Promise<KbzVerificationStatus>;

  /**
   * Polling interval in milliseconds when verifying with backend (default: 2000ms / 2 seconds).
   */
  pollingIntervalMs?: number;

  /**
   * Maximum polling attempts for backend confirmation (default: 15 attempts).
   */
  maxPollingAttempts?: number;
}
